#!/usr/bin/env python3
"""Calibrate the ATB Formation allowance against published ATBs (issue #788, spec 0014, D10, D19).

Each case of `calibration/atb.yaml` is built as an `atb` Design with its tug (the convoy fixture, as
`crates/ovd-format/tests/atb_powering.rs` builds it), run with `ovd run --json` under the current
default resistance method, and its modelled tug power (`formation.tug.installed_power_kw`) is compared
with the published installed power. The in-sample cases fit `formation_resistance_allowance` for an
ATB (least squares on the log of the ratio). A held-out case (a design that publishes no speed) is run
at its stated speed and banded, never fitted. Bands: `calibration/bands.yaml`, `installed_power_kw`.
A band miss is a warning, never a failure.

    python3 tools/atb_calibration.py <path to ovd>            print the report
    python3 tools/atb_calibration.py <path to ovd> --write    write calibration/atb_results.md, the fit
                                                               block of calibration/atb.yaml and
                                                               crates/ovd-format/src/atb_calibration.json
    python3 tools/atb_calibration.py <path to ovd> --check    fail if a written file is stale

The fit is an Estimate: every case says which figures are published and which are assumed.
"""
import copy
import json
import math
import subprocess
import sys
import tempfile
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
CAL = ROOT / "calibration"
CASES = CAL / "atb.yaml"
REPORT = CAL / "atb_results.md"
EMBEDDED = ROOT / "crates/ovd-format/src/atb_calibration.json"
PROFILE = ROOT / "crates/ovd-format/src/builtin_profile.json"
BASE = ROOT / "crates/ovd-format/tests/fixtures/pushed_convoy.vdesign"
HP_KW = 0.7457
# The fit block is the tail of atb.yaml from this line on; the tool writes it, nobody edits it.
FIT_MARK = "# --- GENERATED by python3 tools/atb_calibration.py --write. Do not edit below this line. ---"
# The method the fit is run with: the Defaults Profile's `resistance_method` for a new Option.
METHOD = json.loads(PROFILE.read_text(encoding="utf-8"))["inputs"]["resistance_method"]["default"]


def typed(inputs: dict, key: str, value) -> None:
    inputs[key] = {"value": value, "source": "typed"}


def run_case(ovd: Path, base: dict, c: dict, allowance: float) -> dict:
    """The `formation` block and the `calibration.formation` label of one case at an allowance."""
    d = copy.deepcopy(base)
    i = d["options"][0]["inputs"]
    d["options"][0].pop("results_hash", None)
    t, b = c["tug"], c["barge"]
    typed(i, "formation", {"kind": "atb"})
    typed(i, "tug_included", True)
    typed(i, "tug_stern_form", "transom")
    typed(i, "length_overall_m", b["length_m"])
    typed(i, "beam_m", b["beam_m"])
    typed(i, "moulded_depth_m", b["depth_m"])
    if "draught_m" in b:
        typed(i, "draught_limit_m", b["draught_m"])
    typed(i, "tug_design_speed_kn", c["speed_kn"])
    typed(i, "tug_power_source", "diesel_mechanical")
    typed(i, "tug_propulsor_count", 2)
    typed(i, "tug_length_m", t["length_m"])
    typed(i, "tug_beam_m", t["beam_m"])
    if "draught_m" in t:
        typed(i, "tug_draught_m", t["draught_m"])
    typed(i, "tug_propulsor_type", t["propulsor_type"])
    if "propeller_diameter_m" in t:
        typed(i, "tug_propeller_diameter_m", t["propeller_diameter_m"])
    typed(i, "resistance_method", METHOD)
    typed(i, "formation_resistance_allowance", allowance)
    with tempfile.TemporaryDirectory() as tmp:
        f = Path(tmp) / "case.vdesign"
        f.write_text(json.dumps(d))
        r = subprocess.run([str(ovd), "run", "--json", str(f)], capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(f"ovd failed on {c['id']}: {r.stderr[-400:]}")
    res = json.loads(r.stdout)["options"][0]["results"]
    if "error" in res["formation"]:
        sys.exit(f"{c['id']}: {res['formation']['error']}")
    return {"formation": res["formation"], "label": res["calibration"]["formation"],
            "draught_m": res["results"]["draught_m"]}


def model_power(ovd, base, c, allowance) -> float:
    return run_case(ovd, base, c, allowance)["formation"]["tug"]["installed_power_kw"]


def published_kw(c: dict) -> float:
    return c["installed_power_hp"] * HP_KW


def fit_allowance(ovd, base, cases) -> float:
    """The allowance that minimises the squared log error of the in-sample powers (golden section)."""
    def cost(log_a):
        a = math.exp(log_a)
        return sum(math.log(model_power(ovd, base, c, a) / published_kw(c)) ** 2 for c in cases)
    lo, hi, g = math.log(0.5), math.log(3.0), (math.sqrt(5) - 1) / 2
    x1, x2 = hi - g * (hi - lo), lo + g * (hi - lo)
    f1, f2 = cost(x1), cost(x2)
    for _ in range(30):
        if f1 < f2:
            hi, x2, f2 = x2, x1, f1
            x1 = hi - g * (hi - lo)
            f1 = cost(x1)
        else:
            lo, x1, f1 = x1, x2, f2
            x2 = lo + g * (hi - lo)
            f2 = cost(x2)
    return round(math.exp((lo + hi) / 2), 3)


def basis_text(rows: list[dict], n: int, method: str) -> str:
    """The basis of the fitted allowance: what was fitted, with what, and the held-out misses."""
    fit = [f"{r['c']['id']} {r['err']:+.1f} %" for r in rows if not r["c"].get("held_out")]
    held = [f"{r['c']['id']} {r['err']:+.1f} %" for r in rows if r["c"].get("held_out")]
    out = sum(1 for r in rows if not r["in_range"])
    return (f"Fitted to {n} vessel{'s' if n != 1 else ''} with the {method} resistance method; "
            f"in-sample residuals: {', '.join(fit)}; held-out residuals: {', '.join(held) if held else 'none'}; "
            f"{out} of {len(rows)} cases are outside the method's range, so the speeds are indicative; "
            "barge depths and draughts that the sources do not print are assumed, as each case states.")


def build(ovd: Path) -> tuple[str, str, str]:
    text = CASES.read_text(encoding="utf-8")
    data = yaml.safe_load(text.split(FIT_MARK)[0])
    band = yaml.safe_load((CAL / "bands.yaml").read_text(encoding="utf-8"))["bands"]["installed_power_kw"]
    base = json.loads(BASE.read_text(encoding="utf-8"))
    cases = data["atbs"]
    fit = [c for c in cases if not c.get("held_out")]
    allowance = fit_allowance(ovd, base, fit)
    rows = []
    for c in cases:
        r = run_case(ovd, base, c, allowance)
        r0 = run_case(ovd, base, c, 1.05)
        obs = published_kw(c)
        model = r["formation"]["tug"]["installed_power_kw"]
        err = 100.0 * (model / obs - 1.0)
        lim = float(band["pct"][c["confidence"]])
        check = r["label"]["method_range"]
        rows.append({"c": c, "obs": obs, "model": model, "draught": r["draught_m"],
                     "model105": r0["formation"]["tug"]["installed_power_kw"], "err": err, "band": lim,
                     "inside": abs(err) <= lim, "in_range": check["in_range"], "range_text": check["message"],
                     "converged": r["formation"]["sizing"]["converged"]})
    errs = [r["err"] for r in rows]
    basis = basis_text(rows, len(fit), METHOD)
    md = ["# ATB calibration (issue #788, spec 0014)", "",
          "GENERATED by `python3 tools/atb_calibration.py <ovd> --write` from `calibration/atb.yaml`. Do not edit.", "",
          "A published ATB is run as an `atb` Design with its tug typed, and the installed power the Formation gives "
          "the tug is compared with the published installed power (band `installed_power_kw`). The in-sample cases fit "
          "the ATB Formation resistance allowance; **their residuals are in-sample**. A design that publishes power but "
          f"no speed is held out: it is run at its stated speed, never fitted. Resistance method: `{METHOD}` (the "
          "Defaults Profile's default). A band miss is a warning only.", "",
          f"**Fitted ATB `formation_resistance_allowance`: {allowance}** (status `estimate`). {basis} "
          f"Residual range: {min(errs):+.1f} % to {max(errs):+.1f} %.", "",
          "| Case | Sample | Conf. | Barge draught (m) | Speed (kn) | Published (kW) | Model at 1.05 (kW) | "
          f"Model at {allowance} (kW) | Residual % | Band ± % | vs band | Method range |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        c = r["c"]
        md.append(f"| {c['id']} | {'held out' if c.get('held_out') else 'in-sample'} | {c['confidence']} | "
                  f"{r['draught']:.2f} | {c['speed_kn']:g} | {r['obs']:,.0f} | {r['model105']:,.0f} | {r['model']:,.0f} | "
                  f"{r['err']:+.1f} | ±{r['band']:g} | {'inside' if r['inside'] else '**OUTSIDE**'} | "
                  f"{'inside' if r['in_range'] else 'outside'} |")
    md += ["", "## How each case is run", ""]
    for r in rows:
        c = r["c"]
        md += [f"- **{c['id']}** ({c['name']}; {c['source']}): {c['basis']}"
               + (f" Held out: {c['held_out']}" if c.get("held_out") else ""),
               f"  Method range check: {r['range_text']}."
               + ("" if r["converged"] else " **The sizing loop did not converge.**")]
    md += ["", "## Listed, not run", "", "| Case | Published | Why not run |", "|---|---|---|"]
    for c in data.get("listed_not_run", []):
        md.append(f"| {c['id']} | {c['published']} | {c['not_run']} |")
    md.append("")
    fit_block = {"fit": {"formation_resistance_allowance": {
        "atb": {"value": allowance, "status": "estimate", "method": METHOD, "n": len(fit),
                "evidence": [{"case": c["id"]} for c in fit], "basis": basis}}}}
    yaml_text = text.split(FIT_MARK)[0].rstrip("\n") + "\n\n" + FIT_MARK + "\n" + yaml.safe_dump(fit_block, sort_keys=False)
    embedded = {
        "comment": "GENERATED by python3 tools/atb_calibration.py --write from calibration/atb.yaml. Do not edit.",
        "allowance": allowance,
        "status": "estimate",
        "method": METHOD,
        "basis": basis,
        "residual_range_pct": [round(min(errs), 1), round(max(errs), 1)],
        "cases": [{"id": r["c"]["id"], "sample": "held_out" if r["c"].get("held_out") else "in_sample",
                   "speed_kn": r["c"]["speed_kn"], "published_kw": round(r["obs"], 1),
                   "model_kw": round(r["model"], 1), "residual_pct": round(r["err"], 1),
                   "in_method_range": r["in_range"]} for r in rows],
    }
    return "\n".join(md), yaml_text, json.dumps(embedded, indent=2) + "\n"


def profile_allowance() -> float:
    return json.loads(PROFILE.read_text(encoding="utf-8"))["inputs"]["formation_resistance_allowance"][
        "default_by_formation"]["atb"]


def main(argv: list[str]) -> int:
    args = [a for a in argv if not a.startswith("--")]
    if len(args) != 1:
        print(__doc__)
        return 2
    report, yaml_text, embedded = build(Path(args[0]))
    out = {REPORT: report, CASES: yaml_text, EMBEDDED: embedded}
    if "--write" in argv:
        for path, text in out.items():
            path.write_text(text, encoding="utf-8")
        print("atb_calibration: wrote", ", ".join(str(p.relative_to(ROOT)) for p in out))
    elif "--check" in argv:
        stale = [str(p.relative_to(ROOT)) for p, t in out.items() if p.read_text(encoding="utf-8") != t]
        if stale:
            print("atb_calibration: stale:", ", ".join(stale))
            return 1
        fitted = json.loads(embedded)["allowance"]
        if abs(profile_allowance() - fitted) > 1e-9:
            print("atb_calibration: the Defaults Profile does not take the fitted ATB allowance", fitted)
            return 1
        print("atb_calibration: up to date")
    else:
        print(report)
    for line in report.splitlines():
        if "**OUTSIDE**" in line:
            print(f"::warning title=Calibration band::{line.split('|')[1].strip()}: ATB tug power outside its band")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
