"""The ATB calibration (issue #788, spec 0014 D10, D19): the case file is well formed, the held-out
cases stay out of the fit, and the allowance is pinned to `calibration/atb.yaml` through the file the
engine embeds and the Defaults Profile. The fit itself needs the `ovd` binary:
`python3 tools/atb_calibration.py <ovd> --check` (see the tool)."""

import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
CAL = ROOT / "calibration"
FIT_MARK = "# --- GENERATED by python3 tools/atb_calibration.py --write."


def _file():
    return yaml.safe_load((CAL / "atb.yaml").read_text(encoding="utf-8"))


def _fit():
    return _file()["fit"]["formation_resistance_allowance"]["atb"]


def _embedded():
    return json.loads((ROOT / "crates/ovd-format/src/atb_calibration.json").read_text(encoding="utf-8"))


def _profile_allowance():
    profile = json.loads((ROOT / "crates/ovd-format/src/builtin_profile.json").read_text(encoding="utf-8"))
    return profile["inputs"]["formation_resistance_allowance"]["default_by_formation"]["atb"]


def test_the_allowance_is_pinned_to_the_case_file():
    """Label: property"""
    fit = _fit()
    assert _embedded()["allowance"] == fit["value"]
    assert _profile_allowance() == fit["value"]
    assert _embedded()["method"] == fit["method"]


def test_the_fit_is_an_estimate_that_states_its_basis():
    """Label: property"""
    fit, emb = _fit(), _embedded()
    assert fit["status"] == "estimate" and emb["status"] == "estimate"
    assert fit["basis"] == emb["basis"]
    assert fit["basis"].startswith(f"Fitted to {fit['n']} vessel")
    assert "assumed" in fit["basis"]


def test_held_out_cases_stay_out_of_the_fit():
    """Label: property"""
    cases = _file()["atbs"]
    fit = _fit()
    held = {c["id"] for c in cases if c.get("held_out")}
    fitted = {e["case"] for e in fit["evidence"]}
    assert held and fitted
    assert not held & fitted
    assert fitted == {c["id"] for c in cases if not c.get("held_out")}
    assert fit["n"] == len(fitted)
    samples = {c["id"]: c["sample"] for c in _embedded()["cases"]}
    assert samples == {c["id"]: "held_out" if c.get("held_out") else "in_sample" for c in cases}


def test_every_case_names_its_source_and_its_published_and_assumed_figures():
    """Label: property"""
    for c in _file()["atbs"]:
        assert c["source"] and c["installed_power_hp"] > 0 and c["speed_kn"] > 0
        assert c["basis"].startswith("published:")
        assert c["confidence"] in {"high", "medium", "low"}
        assert c["tug"]["propulsor_type"]
    # An LNG ATB is in the fit (spec 0014 D10).
    assert any("LNG" in c["name"] and not c.get("held_out") for c in _file()["atbs"])


def test_a_listed_design_that_is_not_run_says_why():
    """Label: property"""
    for c in _file()["listed_not_run"]:
        assert c["published"] and c["not_run"]


def test_the_residual_range_spans_every_case():
    """Label: property"""
    emb = _embedded()
    res = [c["residual_pct"] for c in emb["cases"]]
    assert emb["residual_range_pct"] == [min(res), max(res)]
